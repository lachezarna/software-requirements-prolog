% ============================================================
% requirements_data.pl
% Примерен набор от изисквания за малка система за онлайн
% пазаруване. Наборът съзнателно съдържа проблемни изисквания
% (противоречия, нееднозначности, непълнота, цикли в
% зависимостите), за да могат да бъдат тествани правилата за
% анализ от Глава 3/4 (виж т. 5.2 "Тестов набор от изисквания").
% ============================================================

:- ensure_loaded(kb_schema).

:- discontiguous requirement/6.
:- discontiguous action/5.
:- discontiguous attribute/5.
:- discontiguous depends_on/2.

% ------------------------------------------------------------
% Група 1: пряко логическо противоречие (must / must_not)
% req1 и req2 твърдят противоположни неща за едно и също
% действие (system, allow, guest_checkout).
% ------------------------------------------------------------
requirement(req1, functional,
    "Системата трябва да позволява на госта (нерегистриран потребител) да завърши поръчка без регистрация.",
    high, approved, checkout).
action(req1, system, allow, guest_checkout, must).

requirement(req2, functional,
    "Системата не трябва да позволява на нерегистрирани потребители да завършват поръчка.",
    high, approved, checkout).
action(req2, system, allow, guest_checkout, must_not).

% ------------------------------------------------------------
% Група 2: изискване без проблем (за контрол/сравнение)
% ------------------------------------------------------------
requirement(req3, functional,
    "Системата трябва да изпраща имейл потвърждение след успешна поръчка.",
    medium, approved, notifications).
action(req3, system, send, order_confirmation_email, must).

% ------------------------------------------------------------
% Група 3: нееднозначност (неизмерими/субективни термини)
% ------------------------------------------------------------
requirement(req4, nonfunctional,
    "Времето за зареждане на началната страница трябва да бъде бързо.",
    high, draft, frontend).

requirement(req12, functional,
    "Системата трябва да поддържа удобен и лесен за употреба потребителски интерфейс.",
    low, draft, frontend).

% ------------------------------------------------------------
% Група 4: числово (количествено) противоречие
% req5 и req6 задават несъвместими прагове за едно и също
% измеримо свойство (response_time при търсене на продукт).
% ------------------------------------------------------------
requirement(req5, nonfunctional,
    "Времето за отговор на системата при търсене на продукт трябва да бъде не повече от 2 секунди.",
    high, approved, search).
attribute(req5, response_time, lte, 2, seconds).

requirement(req6, nonfunctional,
    "Времето за отговор на системата при търсене на продукт трябва да бъде най-малко 5 секунди.",
    medium, draft, search).
attribute(req6, response_time, gte, 5, seconds).

% ------------------------------------------------------------
% Група 5: изискване без проблем (за контрол/сравнение)
% ------------------------------------------------------------
requirement(req7, functional,
    "Администраторът трябва да може да управлява каталога с продукти.",
    high, approved, catalog).
action(req7, admin, manage, product_catalog, must).

% ------------------------------------------------------------
% Група 6: "мека" несъгласуваност - еднакъв оператор, различни
% прагове за един и същ атрибут (не е строго логическо
% противоречие, но е признак на несъгласуваност/дублиране).
% ------------------------------------------------------------
requirement(req8, nonfunctional,
    "Паролите на потребителите трябва да съдържат поне 8 символа.",
    critical, approved, authentication).
attribute(req8, password_length, gte, 8, chars).

requirement(req9, nonfunctional,
    "Паролите на потребителите трябва да съдържат поне 4 символа.",
    low, draft, authentication).
attribute(req9, password_length, gte, 4, chars).

% ------------------------------------------------------------
% Група 7: непълно изискване (липсват детайли/критерии)
% ------------------------------------------------------------
requirement(req10, functional,
    "Системата трябва да генерира отчети.",
    medium, draft, reporting).

% ------------------------------------------------------------
% Група 8: валидна зависимост между изисквания
% ------------------------------------------------------------
requirement(req11, functional,
    "Системата трябва да позволява на администратора да преглежда поръчки на гости.",
    medium, approved, orders).
action(req11, admin, view, guest_orders, must).
depends_on(req11, req1).
depends_on(req11, req7).

% ------------------------------------------------------------
% Група 9: циклична зависимост (req13 <-> req14)
% ------------------------------------------------------------
requirement(req13, functional,
    "Модулът за плащания трябва да проверява наличността на продукта преди финализиране на поръчката.",
    high, draft, payments).
depends_on(req13, req14).

requirement(req14, functional,
    "Модулът за наличности трябва да се обновява само след успешно потвърдено плащане.",
    high, draft, inventory).
depends_on(req14, req13).
