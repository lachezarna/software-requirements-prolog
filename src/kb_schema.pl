% ============================================================
% kb_schema.pl
% Схема на базата от знания за представяне на софтуерни изисквания.
% Съответства на т. 4.1 "Архитектура на системата" от дипломната
% работа: изискванията се представят като Prolog факти/правила.
% ============================================================

% Файлът не се обявява като Prolog модул умишлено - всички
% факти (requirement/6, action/5, attribute/5, ...) трябва да
% живеят в общото (user) пространство от имена, за да могат
% правилата за анализ в conflict_rules.pl да ги виждат директно.

% ------------------------------------------------------------
% requirement/6
%   requirement(Id, Type, Text, Priority, Status, Module)
%
%   Id       - уникален идентификатор на изискването (атом), напр. req1
%   Type     - functional | nonfunctional
%   Text     - текстово описание на изискването (низ, string)
%   Priority - low | medium | high | critical
%   Status   - draft | reviewed | approved | rejected
%   Module   - компонент/модул от системата, към който принадлежи
%              изискването (атом), напр. authentication, checkout
% ------------------------------------------------------------
:- multifile requirement/6.
:- dynamic   requirement/6.

% ------------------------------------------------------------
% action/5
%   action(Id, Subject, Verb, Object, Modality)
%
%   Семантично (триплетно) представяне на действието, описано в
%   изискване с Id, за да може машината за извод да съпоставя
%   логически твърдения между различни изисквания.
%
%   Subject  - деятел/система, атом, напр. system, admin, guest
%   Verb     - действие, атом, напр. allow, block, display, store
%   Object   - обект на действието, атом, напр. guest_checkout
%   Modality - модалност (деонтична логика):
%                must      - задължително
%                must_not  - забранено
%                should    - препоръчително
%                should_not- непрепоръчително
%                may       - позволено (незадължително)
% ------------------------------------------------------------
:- multifile action/5.
:- dynamic   action/5.

% ------------------------------------------------------------
% attribute/5
%   attribute(Id, Name, Operator, Value, Unit)
%
%   Количествено/нефункционално ограничение, зададено в изискване
%   с Id (напр. производителност, сигурност, наличност).
%
%   Name     - име на атрибута, напр. response_time, uptime,
%              max_users, password_length
%   Operator - eq | lt | lte | gt | gte
%   Value    - число
%   Unit     - мерна единица (атом), напр. seconds, percent, chars,
%              users; none ако е безразмерна величина
% ------------------------------------------------------------
:- multifile attribute/5.
:- dynamic   attribute/5.

% ------------------------------------------------------------
% depends_on/2
%   depends_on(Id1, Id2)  - изискване Id1 зависи от изискване Id2
%                            (Id2 трябва да е удовлетворено, за да
%                            има смисъл/да е изпълнимо Id1)
% ------------------------------------------------------------
:- multifile depends_on/2.
:- dynamic   depends_on/2.

% ------------------------------------------------------------
% excludes/2
%   excludes(Id1, Id2) - изрично декларирана от анализатор
%                          несъвместимост между две изисквания
%                          (използва се за сравнение с автоматично
%                          откритите противоречия в Глава 3/4.2)
% ------------------------------------------------------------
:- multifile excludes/2.
:- dynamic   excludes/2.
